-- Комп «в свободную продажу» больше не публикуется в каталоге до готовности
-- к выдаче. Разово убираем в черновики те, что уже висят на витрине, хотя
-- находятся на ранних этапах (заказ, ожидание железа, сборка и т.п.).
UPDATE pc_builds b
SET status = 'draft', in_stock = FALSE
FROM wip_builds w
WHERE w.build_id = b.id
  AND w.for_sale = TRUE
  AND b.status = 'catalog'
  AND w.stage NOT IN (
    'Проверка перед выдачей', 'Ожидание упаковки',
    'Готов, можно забрать', 'Отнести в сдэк'
  );
